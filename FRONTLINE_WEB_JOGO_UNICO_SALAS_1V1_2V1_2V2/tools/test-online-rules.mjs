import assert from 'node:assert/strict';
import {safePlayerName,validateMotion,rayBodyIntersection} from '../shared/pvp-rules.js';
import {blocked} from '../shared/maps.js';
assert.equal(safePlayerName(' <Mateus> '),'Mateus');
assert.equal(safePlayerName('  Lobo  77  '),'Lobo 77');
assert.equal(safePlayerName(''),'JOGADOR');
assert.ok(safePlayerName('x'.repeat(60)).length<=16);
const start={x:7.5,z:13.5,moveCredit:.45};
const normal=validateMotion('rust',start,7.5,13.68,.04,blocked);
assert.ok(normal.allowed,'Normal 0.18m step accepted');
assert.ok(normal.credit<.45+.04*5.5);
const speed=validateMotion('rust',{...start,moveCredit:0},9.5,13.5,.05,blocked);
assert.ok(!speed.allowed,'2m move within 50ms blocked');
const noTeleport=validateMotion('rust',{x:12.5,z:10.5,moveCredit:1.15},13.5,10.5,.25,blocked);
assert.ok(!noTeleport.allowed,'Through-wall movement blocked even if end-point is open');
assert.ok(!validateMotion('rust',start,NaN,12,.05,blocked).allowed);
const ray={x:1,y:0,z:0},shooter={x:7.5,z:13.5};
assert.equal(rayBodyIntersection(shooter,ray,{x:8.5,z:13.5},33),1);
assert.equal(rayBodyIntersection(shooter,ray,{x:8.5,z:14.5},33),null);
assert.equal(rayBodyIntersection(shooter,ray,{x:3.5,z:13.5},33),null);
console.log('PASS: nicknames sanitized, packet-speed budget, wall sweep, hit ray geometries');
